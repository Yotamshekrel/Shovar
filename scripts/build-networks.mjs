// Compacts the scraped store lists (data/store-lists/*.json) into the bundle-friendly
// format read by src/networks (src/networks/data/<id>.json).
//   node scripts/build-networks.mjs
// Row format: [name, nameEn | null, flags]  (flags: 1 = online-only, 2 = booking required)
// Also writes
//   src/networks/lists.ts            require() table for the bundled lists (Metro needs static paths)
//   docs/catalog/v1/                 the same lists + a manifest, published with the landing page so the app can
//                                    refresh its store lists without a new release (see src/networks/catalogSync.ts)
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'data', 'store-lists');
const outDir = join(root, 'src', 'networks', 'data');
const catalogDir = join(root, 'docs', 'catalog', 'v1');
mkdirSync(outDir, { recursive: true });
rmSync(catalogDir, { recursive: true, force: true });
mkdirSync(join(catalogDir, 'lists'), { recursive: true });

// Trailing words that only say which department/channel of a chain ("קסטרו גברים", "פוקס אונליין").
const SUFFIX_RE = /\s+(אונליין|אוננליין|online|גברים|נשים|ילדים|תינוקות|men|women)$/i;

function clean(s) {
  if (!s) return null;
  let out = s.replace(/\s+/g, ' ').trim();
  out = out.replace(/\s*\((?:לטיני|latin logo|latin)[^)]*\)/i, '').trim();
  return out || null;
}

function canonical(name) {
  let out = name;
  for (let i = 0; i < 2; i++) out = out.replace(SUFFIX_RE, '').trim();
  return out;
}

const index = [];
const catalogLists = {};
for (const file of readdirSync(srcDir).filter((f) => f.endsWith('.json')).sort()) {
  const id = file.replace(/\.json$/, '');
  const json = JSON.parse(readFileSync(join(srcDir, file), 'utf8'));
  const seen = new Map();
  for (const s of json.stores) {
    const rawName = clean(s.name) ?? clean(s.nameEn);
    if (!rawName || s.uncertain) continue;
    // An "…אונליין" suffix is just the web shop of a chain; only lists that are online-only as a whole are flagged.
    const onlineOnly = /online/i.test(json.variant ?? '');
    const name = canonical(rawName);
    const nameEn = canonical(clean(s.nameEn) ?? '') || null;
    if (!name) continue;
    const key = name.toLowerCase();
    let flags = onlineOnly ? 1 : 0;
    if (s.bookingRequired) flags |= 2;
    const prev = seen.get(key);
    if (prev) {
      // A physical entry wins over an online-only duplicate of the same chain.
      if (!(flags & 1)) prev[2] &= ~1;
      prev[1] ??= nameEn && nameEn.toLowerCase() !== key ? nameEn : null;
      continue;
    }
    seen.set(key, [name, nameEn && nameEn.toLowerCase() !== key ? nameEn : null, flags]);
  }
  const stores = [...seen.values()].map((r) => (r[2] ? r : r[1] ? [r[0], r[1], 0] : [r[0], null, 0]));
  writeFileSync(join(outDir, `${id}.json`), JSON.stringify({ id, platform: json.platform, variant: json.variant, updated: json.updated, stores }) + '\n');
  // The published copy only holds what the app reads.
  const body = JSON.stringify({ stores });
  writeFileSync(join(catalogDir, 'lists', `${id}.json`), body + '\n');
  catalogLists[id] = { hash: createHash('sha1').update(body).digest('hex').slice(0, 12), count: stores.length };
  index.push({ id, count: stores.length });
}
console.log(index.map((i) => `${i.id}: ${i.count}`).join('\n'));

// --- card families (networks.json) must point at lists that exist ----------------------------------------
const { networks } = JSON.parse(readFileSync(join(root, 'src', 'networks', 'networks.json'), 'utf8'));
const used = new Set();
for (const n of networks) {
  for (const src of n.sources) {
    used.add(src);
    if (!catalogLists[src]) throw new Error(`networks.json: ${n.id} reads ${src}, but data/store-lists/${src}.json does not exist`);
  }
}
for (const id of Object.keys(catalogLists)) if (!used.has(id)) console.warn(`data/store-lists/${id}.json is not used by any card family in networks.json`);

writeFileSync(
  join(root, 'src', 'networks', 'lists.ts'),
  `// Generated by scripts/build-networks.mjs — do not edit.
import type { RawList } from './registry';

/** Metro needs static require paths, so every bundled list is named here (and loaded lazily). */
export const LOADERS: Record<string, () => RawList> = {
${Object.keys(catalogLists)
  .map((id) => `  ${id}: () => require('./data/${id}.json'),`)
  .join('\n')}
};

/** Content hash of each bundled list, as published in the catalog manifest — a list the app already has is not downloaded again. */
export const BUNDLED_HASHES: Record<string, string> = {
${Object.entries(catalogLists)
  .map(([id, l]) => `  ${id}: '${l.hash}',`)
  .join('\n')}
};
`,
);

const manifest = {
  schema: 1,
  updated: new Date().toISOString().slice(0, 10),
  networks,
  lists: catalogLists,
};
writeFileSync(join(catalogDir, 'manifest.json'), JSON.stringify(manifest) + '\n');
console.log(`catalog: ${networks.length} cards, ${Object.keys(catalogLists).length} lists → docs/catalog/v1`);
